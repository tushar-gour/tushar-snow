import { isDeepStrictEqual } from 'node:util';
import { uid } from '../utils/uid.js';
import { compileQuery } from '../utils/match.js';
import { Document } from './document.js';
import { Schema } from './schema.js';
import { record, own, plain } from '../utils/value.js';
import { StorageError, ConflictError, NotFoundError, ValidationError, QueryError } from '../errors.js';
export class Collection {
  #tail=Promise.resolve(); #ready;
  constructor(name,rootId,drive,schema) {
    this.name=name; this.drive=drive; this.schema=schema instanceof Schema?schema:new Schema(schema); this.rootId=rootId;
  }
  get ready() {
    if(!this.#ready) {this.#ready=Promise.resolve().then(()=>this.drive.ensureFolder(this.name,this.rootId));this.#ready.catch(()=>{this.#ready=undefined;});}
    return this.#ready;
  }
  #run(fn) {const result=this.#tail.then(async()=>fn(await this.ready));this.#tail=result.catch(()=>{});return result;}
  #hydrate(raw,file) {
    if(!plain(raw)||!own(raw,'_id')||typeof raw._id!=='string'||!raw._id||file.name!==`${raw._id}.json`) throw new StorageError(`Document ID or filename mismatch: ${file.name}`);
    try {return {_id:raw._id,...this.schema.validate(raw,{defaults:false})};} catch(cause) {throw new StorageError(`Stored document ${raw._id} failed schema validation`,{cause});}
  }
  async #scan(folder,query) {
    const files=await this.drive.listFiles(folder); const seen=new Set(), rows=[];
    for(const file of files) {
      if(!file.name.endsWith('.json')) continue;
      if(seen.has(file.name)) throw new ConflictError(`Duplicate document filename ${file.name}`);seen.add(file.name);
    }
    for(const file of files) {
      if(!file.name.endsWith('.json')) continue;
      const data=this.#hydrate(await this.drive.readFile(file.id),file);if(query(data)) rows.push({file,data});
    }
    return rows;
  }
  #doc(row) {return new Document(row.data,this,row.file.id);}
  async create(data) {
    record(data,'document');if(own(data,'_id')) throw new ValidationError('_id is generated by Snow');
    const validated=this.schema.validate(data), id=uid(), doc={_id:id,...validated};
    return this.#run(async folder=>{const fileId=await this.drive.writeFile(`${id}.json`,doc,folder);return new Document(doc,this,fileId);});
  }
  async find(query={}) {const test=compileQuery(query);return this.#run(async folder=>(await this.#scan(folder,test)).map(row=>this.#doc(row)));}
  async findOne(query={}) {const test=compileQuery(query);return this.#run(async folder=>{const [row]=await this.#scan(folder,test);return row?this.#doc(row):null;});}
  async countDocuments(query={}) {const test=compileQuery(query);return this.#run(async folder=>(await this.#scan(folder,test)).length);}
  #mutationQuery(query,many=false) {if(!plain(query)||(!many&&!Object.keys(query).length)) throw new QueryError('Mutation requires an explicit query; use {} with *Many only');return compileQuery(query);}
  #patch(update) {
    record(update,'update');if(own(update,'_id')) throw new ValidationError('_id is immutable');
    const fields=this.schema.definition; const result={};
    for(const [key,value] of Object.entries(update)) {
      if(!own(fields,key)) throw new ValidationError(`Unknown update field: ${key}`);
      // Validate/copy provided fields without requiring other fields.
      const schema=new Schema({[key]:fields[key]});
      const validated=schema.validate({[key]:value},{defaults:false});result[key]=validated[key];
    }
    return result;
  }
  async #update(query,update,many) {
    const test=this.#mutationQuery(query,many),patch=this.#patch(update);
    return this.#run(async folder=>{
      const rows=await this.#scan(folder,test), selected=many?rows:rows.slice(0,1);
      const changes=selected.map(row=>({...row,data:{_id:row.data._id,...this.schema.validate({...row.data,...patch},{defaults:false})}}));
      let completed=0;
      try {for(const row of changes){await this.drive.updateFile(row.file.id,row.data);completed++;}}
      catch(cause){if(many) throw new StorageError(`Bulk update failed after ${completed} of ${changes.length} confirmed writes; failing write outcome may be unknown`,{cause});throw cause;}
      return many?changes.length:changes.length?this.#doc(changes[0]):null;
    });
  }
  updateOne(query,update) {return this.#update(query,update,false);}
  updateMany(query,update) {return this.#update(query,update,true);}
  async #delete(query,many) {
    const test=this.#mutationQuery(query,many);
    return this.#run(async folder=>{const rows=await this.#scan(folder,test), selected=many?rows:rows.slice(0,1);let completed=0;
      try {for(const row of selected){await this.drive.deleteFile(row.file.id);completed++;}}
      catch(cause){if(many) throw new StorageError(`Bulk delete failed after ${completed} of ${selected.length} confirmed deletes; failing delete outcome may be unknown`,{cause});throw cause;}
      return many?completed:completed===1;});
  }
  deleteOne(query) {return this.#delete(query,false);}
  deleteMany(query) {return this.#delete(query,true);}
  async saveDocument(fileId,snapshot,data) {
    if(!fileId) throw new NotFoundError('Document has no storage identity');
    const validated={_id:snapshot._id,...this.schema.validate(data,{defaults:false})};
    return this.#run(async folder=>{const rows=await this.#scan(folder,d=>d._id===snapshot._id), row=rows.find(r=>r.file.id===fileId);
      if(!row) throw new NotFoundError('Document no longer exists');
      if(!isDeepStrictEqual(row.data,snapshot)) throw new ConflictError('Document changed since it was loaded; reload before saving');
      await this.drive.updateFile(fileId,validated);return validated;});
  }
  async removeDocument(fileId,id) {
    return this.#run(async folder=>{const rows=await this.#scan(folder,d=>d._id===id);if(!rows.some(r=>r.file.id===fileId))return false;await this.drive.deleteFile(fileId);return true;});
  }
}
